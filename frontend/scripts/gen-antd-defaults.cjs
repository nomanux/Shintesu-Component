/**
 * Writes src/pages/showcase/antdDefaults.ts: Ant Design's default value for
 * every token that src/theme.ts overrides. Run after upgrading antd:
 *
 *   node scripts/gen-antd-defaults.cjs
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const req = (p) => require(path.join(root, "node_modules", p));

// Load theme.ts
const esbuild = req("esbuild");
const built = esbuild.buildSync({
  entryPoints: [path.join(root, "src/theme.ts")],
  bundle: true,
  format: "cjs",
  platform: "node",
  write: false,
});
const mod = { exports: {} };
new Function("module", "exports", "require", built.outputFiles[0].text)(mod, mod.exports, require);
const ours = mod.exports.shComponentTheme;

// Ant Design defaults
const { theme } = req("antd");
const base = theme.getDesignToken();
const lib = (p) => req("antd/lib/" + p);
const componentDefaults = {
  Button: () => lib("button/style/token").prepareComponentToken(base),
  Input: () => lib("input/style/index").initComponentToken(base),
  Select: () => lib("select/style/token").prepareComponentToken(base),
  DatePicker: () => lib("date-picker/style/token").prepareComponentToken(base),
  Table: () => lib("table/style/index").prepareComponentToken(base),
  Radio: () => lib("radio/style/index").prepareComponentToken(base),
  Form: () => lib("form/style/index").prepareComponentToken(base),
  Pagination: () => lib("pagination/style/index").prepareComponentToken(base),
  Menu: () => lib("menu/style/index").prepareComponentToken(base),
};

const fmt = (v) => (typeof v === "string" ? JSON.stringify(v.replace(/\s*\n\s*/g, " ")) : v);
const block = (name, keys, defaults) => {
  const lines = keys.filter((k) => k in defaults).map((k) => `    ${k}: ${fmt(defaults[k])},`);
  return `  ${name}: {\n${lines.join("\n")}\n  },`;
};

const blocks = [block("global", Object.keys(ours.token), base)];
for (const [name, fn] of Object.entries(componentDefaults)) {
  const defaults = { ...base, ...fn() };
  blocks.push(block(name, Object.keys(ours.components[name] ?? {}), defaults));
}

const version = req("antd/package.json").version;
const out = `/**
 * Ant Design ${version} default values for every token that theme.ts overrides.
 * Generated by scripts/gen-antd-defaults.cjs — rerun it after upgrading antd.
 * Keys that are not Ant Design tokens are left out.
 */
export const ANTD_DEFAULTS: Record<string, Record<string, string | number>> = {
${blocks.join("\n")}
};
`;

fs.writeFileSync(path.join(root, "src/pages/showcase/antdDefaults.ts"), out);
console.log(`Wrote antdDefaults.ts (antd ${version})`);
